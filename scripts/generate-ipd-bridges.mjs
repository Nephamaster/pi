#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
for (const name of ["command", "process", "fs"]) {
	const output = `${root}packages/ipd/environments/common/${name}-bridge.mjs`;
	const result = await build({
		absWorkingDir: root, entryPoints: [`packages/ipd/src/environment/bridge/${name}.ts`],
		bundle: true, platform: "node", target: "node24", format: "esm", write: false,
		banner: { js: "// Generated by scripts/generate-ipd-bridges.mjs. Edit src/environment/bridge instead." },
	});
	const content = result.outputFiles[0].text;
	if (process.argv.includes("--check")) {
		if (await readFile(output, "utf8") !== content) throw new Error(`Stale IPD bridge: ${name}; run node scripts/generate-ipd-bridges.mjs`);
	} else await writeFile(output, content);
}
