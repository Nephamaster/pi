#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
	absWorkingDir: root,
	entryPoints: ["packages/ipd/src/visualization/dashboard-client.ts"],
	bundle: true, platform: "browser", target: "es2022", format: "iife", globalName: "IpdDashboard", write: false, charset: "utf8",
});
const style = await readFile(`${root}packages/ipd/src/visualization/dashboard.css`, "utf8");
const script = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const content = `// Generated by scripts/generate-ipd-dashboard.mjs; edit dashboard-client.ts/dashboard.css.\nexport const DASHBOARD_SCRIPT = ${JSON.stringify(script)};\nexport const DASHBOARD_STYLE = ${JSON.stringify(style)};\n`;
const output = `${root}packages/ipd/src/visualization/dashboard-assets.generated.ts`;
if (process.argv.includes("--check")) {
	if (await readFile(output, "utf8") !== content) throw new Error("Stale dashboard assets; run node scripts/generate-ipd-dashboard.mjs");
} else await writeFile(output, content);
